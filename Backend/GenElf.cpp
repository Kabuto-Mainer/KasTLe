/* ============================================================
 * Elf64_Ehdr
 *     Заголовок ELF-файла фиксированного размера в 64 байта. Содержит
 *     магическую сигнатуру, разрядность и порядок байт, тип файла
 *     (ET_EXEC или ET_DYN), архитектуру, точку входа e_entry, а также
 *     смещения, размеры и количество записей таблицы программных
 *     заголовков. Таблица секций здесь не используется, поэтому
 *     соответствующие поля e_shoff, e_shnum, e_shentsize выставлены
 *     в ноль.
 *
 * Elf64_Phdr[]
 *     Массив программных заголовков, расположенный сразу за Ehdr по
 *     смещению e_phoff. Описывает сегменты, на которые ядро и
 *     динамический линковщик опираются при загрузке. Минимальный
 *     набор для исполняемого с динамическим линковщиком:
 *
 *         PT_PHDR      описывает сам этот массив, чтобы ld.so мог
 *                      найти его в уже замапленном образе через
 *                      auxv-вектор AT_PHDR.
 *         PT_INTERP    указывает на NUL-терминированную строку пути
 *                      к динамическому линковщику; ядро читает её при
 *                      execve и запускает ld.so с твоим файлом в
 *                      качестве аргумента.
 *         PT_LOAD × 2  два загружаемых сегмента: один с правами R-X
 *                      (код и константы), другой с R-W (изменяемые
 *                      данные и .got.plt). Раздельные сегменты
 *                      обязательны, потому что mmap раздаёт права на
 *                      уровне страниц.
 *         PT_DYNAMIC   указывает на секцию .dynamic; ld.so находит
 *                      её исключительно через программные заголовки,
 *                      таблицу секций он не читает.
 *         PT_GNU_STACK флагами p_flags сообщает ядру, какие права
 *                      выдать стеку. Без этой записи стек по
 *                      умолчанию делается исполняемым, что нежелательно.
 *
 * ------------------------------------------------------------
 * PT_LOAD сегмент R-X (read + execute)
 * ------------------------------------------------------------
 *
 *     .interp
 *         ASCII-строка вида "/lib64/ld-linux-x86-64.so.2\0".
 *         Физически это те же самые байты, на которые указывает
 *         PT_INTERP, просто рассмотренные как отдельная секция.
 *         Никаких имён библиотек или функций здесь нет — только
 *         путь к динамическому линковщику.
 *
 *     .hash
 *         Хеш-таблица в формате SysV для ускоренного поиска по
 *         .dynsym. Состоит из заголовка (nbuckets, nchain), массива
 *         buckets и массива chain. Используется динамическим
 *         линковщиком ld.so при разрешении символов: ld.so вычисляет
 *         elf_hash от имени, по модулю nbuckets получает индекс
 *         ведра, и идёт по цепочке chain[], пока не найдёт совпадение
 *         по строке либо не дойдёт до терминатора STN_UNDEF.
 *
 *     .dynsym
 *         Массив структур Elf64_Sym по 24 байта. Нулевая запись
 *         всегда пустая (STN_UNDEF). Для нашего исполняемого
 *         содержит три импортируемые функции, у каждой st_shndx
 *         равно SHN_UNDEF, st_value и st_size равны нулю — это
 *         сигнал ld.so разрешить символ при загрузке. В общем
 *         случае в .dynsym могут быть и определённые символы,
 *         экспортируемые наружу (актуально для разделяемых библиотек).
 *
 *     .dynstr
 *         Пул NUL-терминированных строк: имена нужных библиотек
 *         ("libc.so.6") и импортируемых символов ("printf", "calloc",
 *         "free"). Все ссылки на эту секцию — это байтовые смещения
 *         от её начала; именно сюда указывают DT_NEEDED.d_val в
 *         .dynamic и Elf64_Sym.st_name в .dynsym. Первый байт пула
 *         всегда \0, чтобы значение st_name = 0 трактовалось как
 *         отсутствие имени.
 *
 *     .rela.plt
 *         Массив Elf64_Rela по 24 байта, содержит релокации типа
 *         R_X86_64_JUMP_SLOT — по одной на каждую импортируемую
 *         функцию. Каждая запись связывает слот в .got.plt с
 *         символом в .dynsym: r_offset указывает на слот, верхние
 *         32 бита r_info содержат индекс символа, нижние 32 бита —
 *         тип релокации (7 для JUMP_SLOT). Применяются лениво,
 *         при первом вызове функции через PLT.
 *
 *     .rodata
 *         Read-only данные: в нашем случае три строки форматирования
 *         для printf. Адресуются из .text через RIP-относительные
 *         lea-инструкции с disp32, посчитанным на этапе генерации;
 *         никаких runtime-релокаций для доступа к этим строкам не
 *         требуется.
 *
 *     .plt
 *         Таблица стабов вызова внешних функций. PLT[0] — общий
 *         заголовок, в нём push на GOT[1] (link_map) и косвенный
 *         прыжок через GOT[2] (адрес резолвера). PLT[i] для каждой
 *         импортируемой функции состоит из косвенного прыжка через
 *         GOT[3+i-1], push индекса релокации и безусловного прыжка
 *         в PLT[0]. Каждая запись ровно 16 байт. Адреса в косвенных
 *         прыжках задаются 32-битным RIP-относительным смещением.
 *
 *     .text
 *         Машинный код программы: тело _start (на которое указывает
 *         e_entry) и __func__fact. Все ссылки внутри .text и из
 *         .text в .rodata разрешаются на этапе генерации: внутренние
 *         call и jmp получают rel32, RIP-относительные lea получают
 *         disp32. Единственные ссылки, требующие runtime-разрешения, —
 *         это вызовы внешних функций, и они проходят через PLT.
 *
 * ------------------------------------------------------------
 * PT_LOAD сегмент R-W (read + write)
 * ------------------------------------------------------------
 *
 *     .got.plt
 *         Массив 8-байтных слотов, в которые ld.so и резолвер
 *         записывают разрешённые адреса. GOT[0] заполняется нами и
 *         содержит виртуальный адрес .dynamic. GOT[1] и GOT[2]
 *         инициализированы нулями; ld.so при загрузке записывает в
 *         них, соответственно, указатель на link_map и адрес
 *         функции-резолвера. GOT[3+i] изначально содержит адрес
 *         push-инструкции внутри соответствующего PLT-стаба, что
 *         реализует механизм lazy binding: при первом вызове
 *         управление возвращается обратно в стаб и далее в резолвер,
 *         а после успешного разрешения слот перезаписывается реальным
 *         адресом функции в libc.
 *
 *     .dynamic
 *         Массив структур Elf64_Dyn по 16 байт, центральная таблица
 *         динамического линковщика. Каждая запись — это пара
 *         (тег, значение), где значение трактуется либо как число
 *         (размер, индекс), либо как виртуальный адрес другой секции,
 *         в зависимости от тега. Через DT_NEEDED ld.so узнаёт, какие
 *         библиотеки подгрузить; через DT_HASH, DT_STRTAB, DT_SYMTAB,
 *         DT_PLTGOT, DT_JMPREL получает адреса всех остальных
 *         служебных таблиц; через DT_STRSZ, DT_PLTRELSZ — их размеры.
 *         Завершается обязательной записью DT_NULL. Размещается в
 *         RW-сегменте, потому что ld.so в процессе работы патчит
 *         некоторые поля (например, DT_DEBUG).
 *
 *     .data
 *         Пул из глобальных переменных с изменяемым значением.
 *
 * ============================================================
 */


static void emit_elf_header(KTL_GenContext *cont) {
    assert(cont);

    Elf64_Ehdr header = {};

    header.e_ident[EI_MAG0]    = ELFMAG0;
    header.e_ident[EI_MAG1]    = ELFMAG1;
    header.e_ident[EI_MAG2]    = ELFMAG2;
    header.e_ident[EI_MAG3]    = ELFMAG3;
    header.e_ident[EI_CLASS]   = ELFCLASS64;
    header.e_ident[EI_DATA]    = ELFDATA2LSB;
    header.e_ident[EI_VERSION] = EV_CURRENT;
    header.e_ident[EI_OSABI]   = ELFOSABI_SYSV;

    header.e_type      = ET_EXEC;
    header.e_machine   = EM_X86_64;
    header.e_version   = EV_CURRENT;
    header.e_entry     = -1;
    header.e_phoff     = sizeof(Elf64_Ehdr);
    header.e_shoff     = 0;
    header.e_flags     = 0;
    header.e_ehsize    = sizeof(Elf64_Ehdr);
    header.e_phentsize = sizeof(Elf64_Phdr);
    header.e_phnum     = 6;
    header.e_shentsize = 0;
    header.e_shnum     = 0;
    header.e_shstrndx  = 0;


}

